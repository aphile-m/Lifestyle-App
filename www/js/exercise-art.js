const KEYWORDS = [
  [/squat/i, 'squat'],
  [/push[- ]?up|press[- ]?up/i, 'pushup'],
  [/plank|hold/i, 'plank'],
  [/press|overhead|shoulder/i, 'press'],
  [/curl/i, 'curl'],
  [/row|pull/i, 'row'],
  [/lunge|split/i, 'lunge'],
  [/rope|skip|jump/i, 'rope'],
  [/run|jog|walk|treadmill|step|cardio|stride/i, 'run'],
  [/bridge|hinge|deadlift/i, 'squat'],
];

export function exerciseAnim(name, px = 3) {
  const key = (KEYWORDS.find(([re]) => re.test(name || '')) || [null, 'generic'])[1];
  const frames = SPRITES[key];
  const w = 16, h = 14;
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', `0 0 ${w} ${h}`);
  svg.setAttribute('width', w * px);
  svg.setAttribute('height', h * px);
  svg.setAttribute('class', 'ex-px');
  svg.setAttribute('aria-hidden', 'true');
  frames.forEach((rows, i) => {
    const g = document.createElementNS('http://www.w3.org/2000/svg', 'g');
    g.setAttribute('class', 'exf exf-' + (i + 1));
    rows.forEach((row, y) => {
      if (row.length !== w) { console.error('sprite', key, 'frame', i, 'row', y, 'len', row.length); return; }
      [...row].forEach((ch, x) => {
        if (ch === '.') return;
        const color = PAL[ch];
        if (!color) return;
        const r = document.createElementNS('http://www.w3.org/2000/svg', 'rect');
        r.setAttribute('x', x); r.setAttribute('y', y);
        r.setAttribute('width', 1.06); r.setAttribute('height', 1.06);
        r.setAttribute('fill', color);
        g.appendChild(r);
      });
    });
    svg.appendChild(g);
  });
  return svg;
}
