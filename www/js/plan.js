/* plan.js — structured periodisation (SPEC §2.4):
   monthly theme (mesocycle) → weekly focus → Workout of the Day.
   Generated by Vic ONLY after a measure-and-benchmark session (§3.4). */

import { settings, logs } from './store.js';

const MODEL = 'claude-opus-4-8';

/* Latest known value PER METRIC, merged newest-wins across all rows. A measuring
   session gets filled in over several saves — reading only the newest row made
   earlier entries (e.g. this morning's run) vanish behind a later partial save. */
async function mergedLatest(store) {
  const rows = (await logs.all(store)).sort((a, b) => Date.parse(a.ts) - Date.parse(b.ts));
  if (!rows.length) return null;
  const out = {};
  for (const r of rows) {
    for (const [k, v] of Object.entries(r)) {
      if (v != null && k !== 'id' && k !== 'synced') out[k] = v;
    }
  }
  return out; // ts = newest row's ts (the current session date)
}
export const latestMeasurement = () => mergedLatest('measurements');
export const latestBenchmark = () => mergedLatest('benchmarks');
export async function activePlan() {
  const rows = await logs.all('plans');
  return rows.filter(p => p.active).pop() || null;
}

/* Days since a row's ts; null if no row */
export function daysSince(row) {
  return row ? Math.floor((Date.now() - Date.parse(row.ts)) / 86400e3) : null;
}

function planPrompt(profile, measurement, benchmark, weights) {
  return `You are Vic, a top personal trainer, writing a 4-week training plan (one mesocycle).

CLIENT
- Goal: ${profile.goal}. Sustainable rate: ${profile.targetRate}. No crash protocols.
- Injuries/limits: ${profile.injuries || 'none reported'}.
- Equipment available (use ONLY these): ${profile.equipment}.
- Preferred modalities to include: ${profile.modalities}.
- Session time budget: ${profile.sessionMinutes} minutes INCLUDING warm-up and cool-down.
- Latest body measurements: ${JSON.stringify(measurement)}.
- Latest fitness/strength benchmarks: ${JSON.stringify(benchmark)}.
- Recent weight entries (kg): ${JSON.stringify(weights.slice(-5).map(w => w.kg))}.

RULES
- Structure: ONE monthly theme, then per-week themes (week 4 = deload), then sessions.
- 4 sessions/week: 2 strength, 1 run/cardio (street running or treadmill/stepper ok), 1
  conditioning or mobility. Progressive overload week to week — small, attainable jumps.
- Every session fits the time budget: warm-up block (~8 min), main block(s), cool-down
  block (~5 min). Every exercise names its equipment ("bodyweight" counts).
- Calibrate difficulty to the benchmarks — the next step must be hittable.

Return ONLY valid JSON, no markdown fences, exactly this shape:
{"month_theme":"...","rationale":"1-2 sentences, Vic's voice, why this theme for this client",
 "start_date":"${nextMonday()}","weeks":[
   {"week":1,"theme":"...","sessions":[
     {"dow":1,"title":"...","type":"strength|run|conditioning|mobility","duration_min":${profile.sessionMinutes},
      "blocks":[{"name":"Warm-up","minutes":8,"exercises":[
        {"name":"...","equipment":"...","sets":2,"reps":"10","rest_sec":30,"note":"cue or target"}]}]}]}]}
dow is ISO day-of-week (1=Mon…7=Sun). reps may be a count, a duration ("40s") or a distance ("2 km").`;
}

function nextMonday() {
  const d = new Date();
  d.setDate(d.getDate() + ((8 - d.getDay()) % 7 || 7));
  return d.toISOString().slice(0, 10);
}

export async function generatePlan() {
  const apiKey = settings.apiKey;
  if (!apiKey) throw new Error('NO_KEY');
  const [measurement, benchmark, weights] = await Promise.all([
    latestMeasurement(), latestBenchmark(), logs.recent('weights', 28),
  ]);
  if (!measurement && !benchmark) throw new Error('NO_BASELINE');

  const res = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: {
      'content-type': 'application/json',
      'x-api-key': apiKey,
      'anthropic-version': '2023-06-01',
      'anthropic-dangerous-direct-browser-access': 'true',
    },
    body: JSON.stringify({
      model: MODEL, max_tokens: 8000,
      messages: [{ role: 'user', content: planPrompt(settings.profile, measurement, benchmark, weights) }],
    }),
  });
  if (!res.ok) {
    let detail = '';
    try { detail = (await res.json())?.error?.message || ''; } catch {}
    throw new Error(`Plan generation failed (${res.status}). ${detail.slice(0, 140)}`);
  }
  const data = await res.json();
  let text = (data.content || []).find(b => b.type === 'text')?.text.trim() || '';
  text = text.replace(/^```(json)?\s*/i, '').replace(/```\s*$/, '');
  const plan = JSON.parse(text);
  if (!plan.month_theme || !Array.isArray(plan.weeks) || !plan.weeks.length) {
    throw new Error('Vic returned an unusable plan — try again.');
  }
  // deactivate previous plans, store the new one
  const old = await logs.all('plans');
  for (const p of old.filter(p => p.active)) await logs.put('plans', { ...p, active: false });
  await logs.add('plans', { plan, active: true });
  return plan;
}

/* Which session is due today (or next), given the active plan */
export function sessionForToday(plan) {
  const start = Date.parse(plan.start_date + 'T00:00:00');
  const dayIdx = Math.floor((Date.now() - start) / 86400e3);
  const isoDow = ((new Date().getDay() + 6) % 7) + 1; // 1=Mon…7=Sun
  if (dayIdx < 0) return { status: 'starts', when: plan.start_date, week: plan.weeks[0] };
  const weekNo = Math.floor(dayIdx / 7);
  if (weekNo >= plan.weeks.length) return { status: 'finished' };
  const week = plan.weeks[weekNo];
  const today = (week.sessions || []).find(s => s.dow === isoDow);
  if (today) return { status: 'today', week, session: today };
  const next = (week.sessions || []).find(s => s.dow > isoDow) || null;
  return { status: 'rest', week, next };
}
